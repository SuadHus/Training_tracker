// Writes src/lib/lift-plans.ts: where each of the six lifts is drawn on the stage, at both sizes, planned from the motion model and the cameras.
// The page reads the stored plans instead of building six sets and sampling every pose of them on its first frame. Run it with
// `npm run lift:plans` whenever the motion tables or the cameras change; tests/lift-camera.test.ts fails until you do.
import { writeFileSync } from "node:fs";
import { computePlans } from "../src/lib/lift-plan";

const text = `// Generated by scripts/make-lift-plans.ts from the motion model and the cameras: do not edit, run \`npm run lift:plans\`.
import type { Plans } from "./lift-plan";

export const PLANS: Plans = ${JSON.stringify(computePlans())};
`;
writeFileSync(new URL("../src/lib/lift-plans.ts", import.meta.url), text);
console.log(`src/lib/lift-plans.ts: ${(text.length / 1024).toFixed(1)} kB`);
